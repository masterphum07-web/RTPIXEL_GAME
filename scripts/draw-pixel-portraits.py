# Reproducible portrait artwork for RADTECH PIXEL.
# Run with the installed astra-pixel-art skill's pixelart.py exec --file.

def portrait(name, hair, hair_lit, coat, trim, bow=False, cap=False):
    bg = new_canvas(96, 96, name=name + "-background")
    bg.rect(0, 0, 96, 96, "#244475")
    bg.rect(3, 3, 90, 90, "#31588a")
    bg.rect(7, 7, 82, 82, "#3d6aa0")
    bg.rect(7, 7, 82, 5, "#78b8df")
    bg.rect(7, 84, 82, 5, "#203961")
    bg.rect(11, 12, 74, 72, "#5280b4")
    bg.rect(14, 15, 68, 66, "#6090bf")
    for x, y in [(14, 19), (78, 19), (14, 77), (78, 77)]:
        bg.rect(x, y, 4, 4, "#a4d5ef")

    body = new_canvas(96, 96, name=name + "-coat")
    # shoulders, white uniform and shaded lapels
    body.poly([(18, 95), (20, 78), (28, 70), (39, 67), (57, 67), (68, 71), (77, 80), (79, 95)], "#263855")
    body.poly([(20, 95), (23, 80), (31, 73), (41, 70), (55, 70), (66, 74), (74, 82), (76, 95)], coat)
    body.poly([(27, 77), (39, 70), (47, 78), (41, 92), (34, 89)], "#e8f2f5")
    body.poly([(68, 77), (57, 70), (49, 78), (56, 92), (63, 89)], "#d0e2eb")
    body.poly([(40, 70), (48, 78), (44, 86), (39, 77)], trim)
    body.poly([(57, 70), (49, 78), (54, 86), (59, 77)], "#91c8e5")
    body.rect(47, 79, 3, 14, "#53b9e4")
    body.rect(45, 83, 7, 2, "#caefff")
    body.rect(28, 83, 8, 4, "#aec7d5")
    body.rect(61, 84, 8, 4, "#b9d0dc")
    body.rect(29, 86, 7, 2, "#7d9cb4")
    body.rect(61, 86, 7, 2, "#819eb5")
    body.rect(40, 92, 18, 4, "#263f64")

    backhair = new_canvas(96, 96, name=name + "-hair-back")
    backhair.poly([(29, 31), (28, 22), (34, 15), (43, 11), (54, 11), (64, 16), (70, 24), (71, 43), (68, 61), (73, 75), (65, 79), (61, 61), (36, 62), (32, 79), (24, 75), (28, 57)], "#211f2c")
    backhair.poly([(32, 29), (34, 20), (43, 15), (54, 15), (63, 19), (67, 28), (66, 51), (61, 59), (37, 59), (32, 50)], hair)
    backhair.poly([(35, 23), (43, 17), (53, 17), (61, 21), (64, 26), (56, 23), (49, 25), (42, 23)], hair_lit)
    backhair.rect(30, 36, 6, 18, hair)
    backhair.rect(62, 36, 6, 18, hair)

    face = new_canvas(96, 96, name=name + "-face")
    face.rect(31, 31, 5, 22, "#b87470")
    face.rect(60, 31, 5, 22, "#b87470")
    face.poly([(33, 26), (40, 22), (55, 22), (62, 27), (64, 39), (61, 54), (55, 62), (41, 62), (34, 55), (31, 40)], "#e9a889")
    face.poly([(35, 29), (41, 25), (54, 25), (60, 30), (61, 41), (58, 52), (53, 57), (42, 57), (37, 51), (34, 40)], "#f5c5a6")
    face.rect(35, 40, 4, 4, "#ee9c91")
    face.rect(57, 40, 4, 4, "#ee9c91")
    face.rect(38, 34, 8, 7, "#302738")
    face.rect(52, 34, 8, 7, "#302738")
    face.rect(40, 34, 2, 2, "#fff5df")
    face.rect(54, 34, 2, 2, "#fff5df")
    face.rect(42, 37, 2, 3, "#6b92b1")
    face.rect(56, 37, 2, 3, "#6b92b1")
    face.rect(48, 43, 3, 3, "#d58c7d")
    face.rect(46, 49, 7, 2, "#a85e68")
    face.rect(44, 48, 2, 1, "#f4e3cf")
    face.rect(53, 48, 2, 1, "#f4e3cf")

    fringe = new_canvas(96, 96, name=name + "-fringe")
    fringe.poly([(29, 35), (27, 23), (34, 15), (43, 12), (55, 13), (64, 19), (68, 27), (63, 31), (57, 29), (53, 36), (48, 30), (42, 37), (39, 30), (34, 36)], "#211f2c")
    fringe.poly([(32, 26), (38, 18), (48, 16), (57, 19), (63, 24), (56, 22), (50, 26), (44, 23), (38, 29)], hair)
    fringe.poly([(38, 19), (45, 16), (54, 18), (47, 19), (43, 23)], hair_lit)
    fringe.rect(35, 26, 3, 6, hair_lit)
    fringe.rect(50, 24, 2, 5, "#553a45")
    fringe.rect(58, 26, 3, 4, "#553a45")
    if bow:
        fringe.poly([(27, 23), (31, 17), (37, 19), (34, 24), (38, 28), (33, 31), (28, 28)], "#d95869")
        fringe.rect(31, 22, 3, 3, "#ffe3a1")
    if cap:
        fringe.rect(35, 10, 26, 5, "#f4f0e8")
        fringe.rect(31, 14, 34, 4, "#d8e7ed")
        fringe.rect(46, 10, 5, 9, "#d54c5e")
        fringe.rect(44, 12, 9, 4, "#d54c5e")

    result = flatten([bg, body, backhair, face, fringe], name=name + "-portrait")
    return save(name, canvas=result, scales=(1, 4))

student = portrait("student-portrait", "#3e2b36", "#8a5962", "#edf3f3", "#3479bd")
mentor = portrait("mentor-portrait", "#533440", "#a66f70", "#f6f1e8", "#59b6cf", bow=True, cap=True)
